// 응원톡 자동 검열. 보내기 전에 서버가 거른다 (신고 3번 숨김은 그대로 남는다).
//  - 욕설·비하·혐오·음란: 띄어쓰기, 기호, 숫자를 끼워 넣어 피해 가는 것까지 (씨1발, ㅅ ㅂ, 시.발)
//  - 광고·도배: 링크, 전화번호, 오픈채팅, 같은 글자 길게 반복
//  멀쩡한 낱말이 걸리지 않게 예외(시발점, 십자가…)를 먼저 지운다.

// 비교용으로 다듬기: 소문자, 끼워 넣은 숫자·기호·공백 제거 (씨1발 → 씨발)
export function normalize(text) {
  return String(text ?? '')
    .toLowerCase()
    .replace(/[0-9]/g, '')
    .replace(/[\s\p{P}\p{S}_]/gu, '');
}

// 걸리면 안 되는 낱말 (정규화한 글자 기준)
const ALLOW = ['시발점', '시발역', '발사', '병신년', '십자가', '십장생', '새끼손가락', '새끼발가락', '개나리', '지랄탄'];

// 막는 표현 (정규화한 글자 기준 정규식 조각)
const BLOCK = [
  // 욕설
  '씨발', '씨빨', '씨바', '시발', '시바ㄹ', '쓰발', '쒸발', '씹', 'ㅅㅂ', 'ㅆㅂ', 'ㅅㅣ발', 'ㅆㅣ발', 'sibal', 'ssibal', 'tlqkf',
  '병신', '븅신', '빙신', 'ㅂㅅ', 'qudtls',
  '좆', '존나', '졸라', 'ㅈㄴ', '개새', '개색', '개세', '새끼야', '새기야', '색기', 'ㅅㄲ',
  '지랄', 'ㅈㄹ', '염병', '엠창', '애미', '애비', '느금', '니미', '니엄', '느그엄', '늬애', '썅', '미친놈', '미친년', '미친새', '닥쳐', '꺼져',
  'fuck', 'shit', 'bitch',
  // 비하·혐오 (지역·여성·남성·장애)
  '홍어', '전라디언', '경상디언', '과메기', '김치녀', '한남충', '맘충', '틀딱', '장애인새', '애자',
  // 음란
  '섹스', '야동', '꼬추', 'sex', 'porn',   // '보지·자지'는 '보지 마', '자지 마'와 겹쳐 뺀다
];
const BLOCK_RE = new RegExp(BLOCK.join('|'));

const SPAM = [
  /https?:\/\//i, /www\./i, /\.(com|net|kr|co|io|me|ly|gg)(\/|\b)/i,          // 링크
  /open\.kakao|오픈채팅|오픈톡방|텔레그램|텔레|카톡방|discord\.gg/i,           // 다른 방으로 끌기
  /01[016789][-.\s]?\d{3,4}[-.\s]?\d{4}/,                                    // 휴대폰 번호
  /(토토|배팅|베팅|먹튀|카지노|바카라|사다리|픽스터)/,                           // 도박 광고
];

/** null 이면 통과, 아니면 사람에게 보여 줄 이유 */
export function screen(text) {
  const raw = String(text ?? '');
  if (SPAM.some((re) => re.test(raw))) return '링크·연락처·광고는 보낼 수 없어요';
  if (/(.)\1{9,}/u.test(raw.replace(/\s/g, ''))) return '같은 글자를 너무 많이 반복했어요';
  let n = normalize(raw);
  for (const w of ALLOW) n = n.split(w).join('');
  if (BLOCK_RE.test(n)) return '욕설이나 비하 표현은 보낼 수 없어요';
  return null;
}
